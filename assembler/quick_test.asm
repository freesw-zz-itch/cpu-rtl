# ============================================================
# 测试: ADDI 和 SUBI 指令
# ============================================================

_start:
    # 测试 ADDI 立即数加法
    ADDI R1, R0, #1       ; R1 = 1
    ADDI R2, R0, #2       ; R2 = 2
    ADD  R3, R1, R2       ; R3 = 3

    # 测试 SUBI 立即数减法
    SUBI R4, R3, #1       ; R4 = 3 - 1 = 2
    SUBI R5, R3, #3       ; R5 = 3 - 3 = 0

    # 测试 ADDI 负数立即数
    ADDI R6, R0, #-1      ; R6 = -1
    ADDI R7, R6, #3       ; R7 = -1 + 3 = 2

    # 测试 SUBI 负数立即数 (减负数 = 加)
    SUBI R8, R0, #-1      ; R8 = 0 - (-1) = 1
    SUBI R9, R8, #-2      ; R9 = 1 - (-2) = 3

    # 分支测试
    BEQ R3, R9, _end      # 如果 R3 == R9，跳转到结束

_end:
    NOP                   # 结束
