# ============================================================
# 测试程序: 计算 (10 + 5) * 2 = 30
# ============================================================

# 初始化寄存器
ADD R1, R0, #10    # R1 = 10
ADD R2, R0, #5     # R2 = 5

# 算术运算
ADD R3, R1, R2     # R3 = 15
SUB R4, R1, R2     # R4 = 5
MUL R5, R1, R2     # R5 = 50
DIV R6, R1, R2     # R6 = 2

# 逻辑运算
AND R7, R1, R2     # R7 = 0
OR  R8, R1, R2     # R8 = 15
XOR R9, R1, R2     # R9 = 15

# 移位操作
SHL R10, R1, #1    # R10 = 20
SHR R11, R1, #1    # R11 = 5

# 存储和加载
SW R1, R0, #0      # mem[0] = 10
LW R12, R0, #0     # R12 = 10

# 分支测试
BEQ R12, R1, #4    # 相等，跳转到 +4
JMP #16            # 跳转到结束

# 中断测试
INT                # 触发中断
IRET               # 中断返回

# NOP 填充
NOP
NOP
