# ============================================================
# 测试 BEQ 和 JMP 跳转地址
# ============================================================

_start:
    MOVE R1, #10
    MOVE R2, #10
    BEQ R1, R2, _equal    # 跳转到 _equal (索引地址 4)

_equal:
    MOVE R3, #1

    JMP _start            # 跳转到 _start (索引地址 0)

_end:
    NOP